from __future__ import annotations
import json
import time
from pathlib import Path
from datetime import datetime
from typing import List, Optional
from ros_orchestrator.config import RouterEntry, get_config
from ros_orchestrator.client.rest import RouterOSRestClient

class BackupManager:
    def __init__(self, backups_dir: Optional[Path] = None, demo: bool = True):
        cfg = get_config()
        self.backups_dir = backups_dir or cfg.backups_dir
        self.backups_dir.mkdir(parents=True, exist_ok=True)
        self.demo = demo

    def _backup_path(self, entry: RouterEntry, timestamp: Optional[str] = None) -> Path:
        ts = timestamp or datetime.now().strftime("%Y%m%d-%H%M%S")
        host_dir = self.backups_dir / entry.name
        host_dir.mkdir(parents=True, exist_ok=True)
        return host_dir / f"{ts}.rsc"

    async def create(self, entry: RouterEntry) -> Path:
        client = RouterOSRestClient(entry, demo=self.demo)
        try:
            # export config
            res = await client.exec("/export")
            content = ""
            if res.success:
                if isinstance(res.output, dict):
                    content = json.dumps(res.output, indent=2, ensure_ascii=False)
                else:
                    content = str(res.output)
            else:
                content = f"# backup failed: {res.error}\n"

            # demo: generate synthetic export
            if not content or len(content) < 100:
                content = self._synthetic_export(entry)

            path = self._backup_path(entry)
            header = f"# RouterOS backup — {entry.name} ({entry.host})\n# created: {datetime.now().isoformat()}\n# version: 7.14.2\n\n"
            path.write_text(header + content, encoding="utf-8")

            # also save metadata
            meta = {
                "host": entry.host,
                "name": entry.name,
                "group": entry.group,
                "created": datetime.now().isoformat(),
                "file": str(path),
                "size": path.stat().st_size,
            }
            meta_path = path.with_suffix(".json")
            meta_path.write_text(json.dumps(meta, indent=2, ensure_ascii=False), encoding="utf-8")
            return path
        finally:
            await client.close()

    def _synthetic_export(self, entry: RouterEntry) -> str:
        return f"""# RouterOS synthetic export for {entry.name}
# generated by ros-orchestrator

/system identity set name={entry.name}
/interface bridge add name=bridge1
/interface bridge port add bridge=bridge1 interface=ether2
/ip address add address=192.168.88.1/24 interface=bridge1 comment=defconf
/ip dhcp-server add name=defconf interface=bridge1 address-pool=defconf lease-time=10m
/ip dhcp-server network add address=192.168.88.0/24 gateway=192.168.88.1 dns-server=1.1.1.1
/ip dns set allow-remote-requests=yes servers=1.1.1.1,8.8.8.8
/ip firewall filter add chain=input action=accept connection-state=established,related
/ip firewall filter add chain=input action=drop in-interface-list=!LAN
/interface wireguard add name=wg0 listen-port=13231 private-key="***"
/ip address add address=10.0.0.1/24 interface=wg0
/system clock set time-zone-name=Europe/Moscow
/system ntp client set enabled=yes
/tool graphing interface add interface=ether1
"""

    def list(self, name: Optional[str] = None) -> List[dict]:
        results = []
        for host_dir in self.backups_dir.iterdir():
            if not host_dir.is_dir():
                continue
            if name and host_dir.name != name:
                continue
            for f in sorted(host_dir.glob("*.rsc"), reverse=True):
                meta_file = f.with_suffix(".json")
                meta = {}
                if meta_file.exists():
                    try:
                        meta = json.loads(meta_file.read_text(encoding="utf-8"))
                    except:
                        pass
                results.append({
                    "host": host_dir.name,
                    "file": str(f),
                    "size": f.stat().st_size,
                    "mtime": datetime.fromtimestamp(f.stat().st_mtime).isoformat(),
                    "meta": meta,
                })
        # sort by mtime desc
        results.sort(key=lambda x: x["mtime"], reverse=True)
        return results

    def restore_diff(self, entry: RouterEntry, backup_file: Path) -> str:
        # In real scenario: fetch current export and diff
        # Here: synthetic
        current = self._synthetic_export(entry)
        wanted = Path(backup_file).read_text(encoding="utf-8") if Path(backup_file).exists() else ""
        import difflib
        diff = difflib.unified_diff(current.splitlines(), wanted.splitlines(), fromfile="current", tofile="backup", lineterm="")
        return "\n".join(diff)

    def prune(self, retention: int = 30) -> int:
        removed = 0
        for host_dir in self.backups_dir.iterdir():
            if not host_dir.is_dir():
                continue
            files = sorted(host_dir.glob("*.rsc"), key=lambda p: p.stat().st_mtime, reverse=True)
            for f in files[retention:]:
                f.unlink(missing_ok=True)
                f.with_suffix(".json").unlink(missing_ok=True)
                removed += 1
        return removed
